#pragma once

#include <cstddef>
#include <deque>
#include <optional>
#include <vector>

namespace cam::timing {

/// Покрыт ли момент монотонных часов записанным потоком.
enum class Coverage {
  /// Покрыт: время файла известно.
  Known,
  /// Не покрыт и уже не будет покрыт: момент в паузе. Кадр такого момента в
  /// файл не попадает — для него нет сэмплов.
  Gap,
  /// Момент позже последней пары: ответ будет, когда придут следующие блоки.
  NotYet,
};

struct StreamTime {
  Coverage coverage = Coverage::NotYet;
  /// Время файла в секундах, если момент покрыт.
  double seconds = 0.0;
};

/// Мост часов (design.md D5): связь «монотонное время ↔ время записанного
/// потока».
///
/// Пары приходят от блоков записи: в момент `monotonic` звучало (или
/// обрабатывалось) время файла `stream`. Время файла момента — момент плюс
/// средний сдвиг «время файла − монотонное» пар в окне вокруг него, то есть
/// прямая с наклоном 1 через середину окна. Наклон не оценивается: часы
/// звуковой карты расходятся с монотонными на сотни миллионных долей, и за
/// окно это доли миллисекунды. Окно короткое и стоит вокруг момента: так
/// гасится дрожание пачек, а медленное блуждание слышимой позиции хоста
/// отслеживается (findings.md — задержка вывода). Пары дальше четырёх
/// медианных отклонений в среднее не входят.
///
/// Связь рвётся на паузе: сэмплов нет, а монотонное время идёт. Пара, далёкая
/// от прямой, начинает новый отрезок; моменты между отрезками — разрыв.
class ClockBridge {
public:
  struct Settings {
    /// Ширина окна вокруг момента, секунды. У краёв отрезка окно той же
    /// ширины прижимается к краю.
    double window = 1.0;
    /// Сколько секунд пар отрезка помнить.
    double memory = 10.0;
    /// Пара дальше этого от прямой начинает новый отрезок. С запасом больше
    /// дрожания: у PulseAudio блоки идут пачками, отклонение до 0.2 с
    /// (findings.md — дрожание аудиохука).
    double breakThreshold = 0.3;
    /// Сколько последних отрезков помнить.
    std::size_t keptSegments = 4;
  };

  ClockBridge();
  explicit ClockBridge(Settings settings);

  /// Пара от блока записи. Пары идут в порядке блоков.
  void add(double monotonic, double stream);

  /// Время файла для момента монотонных часов. Момент раньше первой пары
  /// переводится по продолжению прямой назад: время файла выходит меньше
  /// первого, а до начала записи — отрицательным.
  StreamTime streamAt(double monotonic) const;

  /// Время файла по прямой у конца последнего отрезка — и для моментов после
  /// его последней пары, когда пар больше не будет. Пусто — если пар нет или
  /// момент раньше последнего отрезка.
  std::optional<double> extrapolate(double monotonic) const;

  /// Время файла для момента больше не изменится: пары после него заполнили
  /// окно, или его отрезок кончился.
  bool settled(double monotonic) const;

  /// Последний момент, время файла которого больше не изменится. Пусто —
  /// пока пар последнего отрезка меньше, чем на окно.
  std::optional<double> settledUntil() const;

  std::size_t segmentCount() const { return segments_.size(); }

private:
  struct Pair {
    double monotonic;
    double stream;
  };

  struct Segment {
    std::deque<Pair> pairs;
    Pair first{};
    Pair last{};
  };

  /// Начало окна для момента: окно шириной `window` вокруг момента,
  /// прижатое к краям отрезка.
  double windowStart(const Segment &segment, double monotonic) const;

  /// Время файла момента по парам отрезка в окне вокруг него.
  double streamIn(const Segment &segment, double monotonic) const;

  Settings settings_;
  std::vector<Segment> segments_;
  /// Первый отрезок забыт: моменты до оставшихся — уже пауза, а не начало.
  bool firstForgotten_ = false;
};

} // namespace cam::timing
